"""
============================================================
面试版：Agentic RAG 的提示词设计
============================================================
提示词采用模块化设计，分为：
1. 生成提示词 - 根据上下文生成答案
2. 查询重写提示词 - 将原问题改写得更清晰
3. HyDE 提示词 - 生成假设性文档用于检索增强
4. Step-back 提示词 - 生成抽象退步问题用于多路检索
5. 相关性评分提示词 - 判断文档是否与问题相关
6. 综合评分提示词 - 带理由的相关性评分
============================================================
"""

# ================================================================
# 生成答案提示词
# ================================================================
GENERATE_PROMPT = """你是一个专业的AI助手。根据以下上下文信息，回答用户的问题。

上下文信息：
{context}

用户问题：{question}

要求：
1. 只根据提供的上下文信息回答问题
2. 如果上下文中没有相关信息，请明确说明"我没有找到相关信息"
3. 回答要准确、简洁、有条理
4. 如果涉及代码，请给出完整的代码示例

回答："""

# ================================================================
# 查询重写提示词（Agentic RAG 核心）
# ================================================================
REWRITE_QUERY_PROMPT = """你是一个专业的查询改写专家。将用户的问题改写得更清晰、更适合检索。

原问题：{question}

要求：
1. 去除模糊表述，使问题更具体
2. 补充必要的上下文信息
3. 使用更精确的专业术语
4. 保持原问题的核心意图

改写后的问题："""

# ================================================================
# HyDE 假设性文档生成提示词
# ================================================================
HYDE_PROMPT = """你是一个专业的技术文档撰写专家。请基于用户问题生成一段"假设性文档"，内容应像知识库里的真实技术资料片段。

用户问题：{question}

要求：
1. 用陈述句写，像知识库里的一篇真实文档
2. 内容应与问题语义相关，包含可能的细节和关键词
3. 控制在 150 字以内
4. 只输出文档正文，不要标题或解释

假设性文档："""

# ================================================================
# Step-back 退步问题生成提示词
# ================================================================
STEP_BACK_QUESTION_PROMPT = """你是一个查询优化专家。将用户的具体问题抽象成一个更高层次、更通用的问题。

原问题：{question}

要求：
1. 生成一个更高层次的抽象问题
2. 去除具体的名称、日期、数字等细节
3. 聚焦于通用概念和原理
4. 只输出一句话，不要解释

抽象问题："""

# ================================================================
# 子查询拆解提示词（复杂问题自动拆解）
# ================================================================
DECOMPOSE_QUERY_PROMPT = """你是一个查询分析专家。判断用户问题是否需要拆解成多个子问题来检索。

用户问题：{question}

判断标准：
- 如果问题涉及多个独立主题（不同技术/产品/概念），需要拆解
- 如果问题可以一次性从一篇文档中回答，不需要拆解
- 最多拆成 3 个子问题

输出格式：先判断是否需要拆解，再给出子问题。
不需要拆解时输出：SIMPLE
需要拆解时输出：
子问题1：...
子问题2：..."""

# ================================================================
# 相关性评分提示词（Agentic RAG 核心）
# ================================================================
GRADE_DOCUMENTS_PROMPT = """你是一个文档相关性评估专家。判断以下文档是否与用户问题相关。

用户问题：{question}

文档内容：
{document}

评估标准：
- 相关：文档内容包含有助于回答用户问题的信息
- 不相关：文档内容与用户问题无关或关系很小

请只回答"相关"或"不相关"，不要做其他解释。"""

# ================================================================
# 综合评分提示词（返回理由）
# ================================================================
GRADE_DOCUMENTS_WITH_REASON_PROMPT = """你是一个文档相关性评估专家。判断以下文档是否与用户问题相关。

用户问题：{question}

文档内容：
{document}

请判断这个文档是否相关，并给出简短的理由。
回答格式：
相关/不相关：{你的判断}
理由：{你的理由}"""

# ================================================================
# 检索失败分类提示词（v3.0：按失败原因路由）
# ================================================================
CLASSIFY_FAILURE_PROMPT = """你是一个 RAG 系统诊断专家。分析：为什么检索到的文档都无法回答用户问题？

用户问题：{question}
检索到的文档摘要：{doc_summaries}

失败类型：
- ambiguous_query：问题太模糊，改写后可能搜到
- missing_knowledge：知识库里确实没有相关信息，应诚实拒答
- multi_hop_query：需跨文档综合，应拆解为子问题
- retrieval_failure：检索策略问题，应调整参数重试

请只输出失败类型（一行）："""

# ================================================================
# 证据锚定生成提示词（v3.0：每项声明必须有文档依据）
# ================================================================
GROUNDED_GENERATE_PROMPT = """你是一个严谨的技术专家。根据以下文档回答问题。

{context}

用户问题：{question}

严格规则：
1. 每个事实性声明必须标注来源于哪个文档编号（如 [文档1]）
2. 禁止从文档的元数据（作者、来源文件名、仓库名）推断事实关系
3. 禁止使用文档外的知识
4. 如果某个子问题无法在文档中找到充分证据，明确说"未找到足够证据"
5. 不要编造文档中没有的细节

回答："""
